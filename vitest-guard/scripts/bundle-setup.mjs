// Builds src/setup.bundle.mjs: setup + realm + fingerprint in ONE module. In vm pools every setup module is
// fetched and evaluated again for every test file, so module count is the dominant overhead of the layer.
import fs from 'node:fs';
const dir = new URL('../src/', import.meta.url);
const read = (f) => fs.readFileSync(new URL(f, dir), 'utf8');
const nodeImports = new Map();
const strip = (src, ns) => src.replace(/^import\s+(.+?)\s+from\s+'(node:[^']+|vitest)';\n/gm, (m, what, from) => { (nodeImports.get(from) || nodeImports.set(from, new Set()).get(from)).add(what); return ''; })
  .replace(/^import \* as (\w+) from '\.\/(\w+)\.mjs';\n/gm, '')
  .replace(/^import \{[^}]+\} from '\.\/\w+\.mjs';\n/gm, '');
const realm = strip(read('realm.mjs')).replace(/^export /gm, '');
const fpSrc = strip(read('fingerprint.mjs'));
const fpNames = [...fpSrc.matchAll(/^export (?:const|function|let)\s+(\w+)/gm)].map((m) => m[1]);
const fp = `const fp = (() => {\n${fpSrc.replace(/^export /gm, '')}\nreturn { ${fpNames.join(', ')} };\n})();\n`;
const setup = strip(read('setup.mjs'));
let header = '// GENERATED by scripts/bundle-setup.mjs from setup.mjs + realm.mjs + fingerprint.mjs - do not edit\n';
for (const [from, whats] of nodeImports) {
  const named = new Set(), defaults = new Set();
  for (const w of whats) { const m = w.match(/^\{(.+)\}$/); if (m) m[1].split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => named.add(n)); else defaults.add(w); }
  for (const d of defaults) header += `import ${d} from '${from}';\n`;
  if (named.size) header += `import { ${[...named].join(', ')} } from '${from}';\n`;
}
const bundle = header + realm + '\n' + fp + '\n' + setup;
if (process.argv.includes('--check')) {
  // CI: the committed bundle must be what the sources produce
  let cur = ''; try { cur = fs.readFileSync(new URL('setup.bundle.mjs', dir), 'utf8'); } catch {}
  if (cur !== bundle) { console.error('src/setup.bundle.mjs is stale: run `npm run build` and commit the result'); process.exit(1); }
  console.log('src/setup.bundle.mjs is up to date');
} else {
  let cur = null; try { cur = fs.readFileSync(new URL('setup.bundle.mjs', dir), 'utf8'); } catch {}
  if (cur !== bundle) fs.writeFileSync(new URL('setup.bundle.mjs', dir), bundle); // unchanged: keep the mtime
  console.log('written src/setup.bundle.mjs');
}
