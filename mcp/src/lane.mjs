// Lane process: one warm Vitest instance (Node API) with the vto collector, driven by the daemon
// over the child_process IPC channel (works the same on Linux, macOS and Windows).
// The daemon runs two lanes: "main" (affected/full/explicit runs) and "fix" (targeted re-runs of
// already-failed tests while the main run continues). Each lane has its own raw dir
// (VTO_RAW_DIR is read by the collector when a worker starts).
//
// messages in : {type:'run', runId, specs:[{file, names?}]|null, bail?}, {type:'list'}, {type:'cancel'}, {type:'close'}
// messages out: {type:'ready', info}, {type:'ev', ev:{…}}, {type:'done', runId, …}, {type:'list', files}, {type:'error', message}
import { createRequire } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import { slash } from './platform.mjs';
import { summarizeGuard } from './guard-label.mjs';
import { compactError } from './format.mjs';
import { Console } from 'node:console';
import { Writable } from 'node:stream';
import { StateDir, copyPrivate, writePrivate } from './safefs.mjs';

const opts = JSON.parse(process.env.VTO_LANE_OPTS || '{}');
const root = opts.root;
const here = path.dirname(fileURLToPath(import.meta.url));
const collectorDir = opts.collectorDir || path.resolve(here, '../../collector');
const send = (m) => { try { process.send(m); } catch {} };
const rawDir = process.env.VTO_RAW_DIR;

process.chdir(root);
process.on('uncaughtException', (e) => send({ type: 'error', message: `lane: ${e?.stack || e}` }));
process.on('unhandledRejection', (e) => send({ type: 'error', message: `lane: ${e?.stack || e}` }));

const req = createRequire(path.join(root, 'package.json'));
let vitestEntry;
try { vitestEntry = req.resolve('vitest/node'); } catch { send({ type: 'fatal', message: `cannot find "vitest" from ${root}` }); process.exit(2); }
const vitestNode = await import(pathToFileURL(vitestEntry).href);
const { createVitest } = vitestNode;
const vitestVersion = req('vitest/package.json').version;

// setup files must live inside the project (Vite fs allow-list, `vitest` resolves to the project copy);
// .vto/setup/ instead of node_modules/.vto/: node_modules may be shared (symlink, pnpm store, monorepo)
// N5: .vto/ can be supplied by the repository – every component is checked, nothing is written through a symlink
const sd = new StateDir(root, '.vto');
const nmDir = sd.dir('setup');
const copy = (src, name) => { const dst = path.join(nmDir, name); copyPrivate(src, dst); return dst; };
const setupFile = copy(path.join(collectorDir, 'setup-v2.mjs'), 'setup-v2.mjs');
const envProbe = copy(path.join(here, 'collector-ext', 'setup-env-probe.mjs'), 'setup-env-probe.mjs');

// ---- pool / vitest-guard ---------------------------------------------------------------------------
// U-6: 'config' (default) = the pool of the project's own Vitest config; nothing is overridden
const pool = opts.pool || 'config';
const cliOptions = {};
let configFile = opts.configFile || undefined;
if (pool === 'auto' && !process.env.VITEST_GUARD_MODE) process.env.VITEST_GUARD_MODE = 'vm';   // only affects vitest-guard configs
if ((pool === 'vm' || pool === 'shared') && !process.env.VITEST_GUARD_MODE) process.env.VITEST_GUARD_MODE = pool;
if (['forks', 'threads', 'vmThreads', 'vmForks'].includes(pool)) {
  cliOptions.pool = pool;
  if (pool === 'forks' && !process.env.VITEST_GUARD_MODE) process.env.VITEST_GUARD_MODE = 'isolated'; // vitest-guard configs: plain forks
}
if (opts.environment) cliOptions.environment = opts.environment;
if ((pool === 'vm' || pool === 'shared') && opts.wrapVitestGuard) configFile = writeVitestGuardWrapper(opts.wrapVitestGuard, pool);
if (opts.maxWorkers) cliOptions.maxWorkers = opts.maxWorkers;

function writeVitestGuardWrapper({ userConfig, vitestGuard }, mode) {
  const guardSetup = copy(path.join(path.dirname(vitestGuard), 'setup.bundle.mjs'), 'vitest-guard-setup.mjs');
  const f = path.join(nmDir, `vitest.vto-vmguard-${mode}.config.mjs`); // per mode: dom and node lanes may use different modes
  writePrivate(f, `// generated by vto daemon: user config wrapped with vitest-guard (mode ${mode})
import user from ${JSON.stringify(pathToFileURL(userConfig).href)};
import { defineVitestGuardConfig, SETUP_FILE } from ${JSON.stringify(pathToFileURL(vitestGuard).href)};
const base = typeof user === 'function' ? await user({ mode: 'test', command: 'serve' }) : user;
const out = defineVitestGuardConfig({ root: ${JSON.stringify(root)}, ...base }, { mode: ${JSON.stringify(mode)} });
const fix = (t) => { if (t?.setupFiles) t.setupFiles = t.setupFiles.map((s) => (s === SETUP_FILE ? ${JSON.stringify(guardSetup)} : s)); };
fix(out.test); for (const p of out.test?.projects ?? []) fix(p.test);
export default out;
`);
  return f;
}

// ---- reporter → events ---------------------------------------------------------------------------
let cur = null; // current run
const relp = (f) => slash(path.relative(root, f));
const consoleBuf = new Map(); // task id → [text]
const failedTasks = new Map(); // task id → test id (this run)
const reporter = {
  onTestModuleStart(m) {
    if (!cur) return;
    send({ type: 'ev', ev: { ev: 'file-start', runId: cur.runId, file: relp(m.moduleId), project: m.project.name ? (opts.group ? `${m.project.name}:${opts.group}` : m.project.name) : opts.group || '' } });
  },
  onUserConsoleLog(log) {
    if (!log.taskId) return;
    const line = `[${log.type}] ${String(log.content).replace(/\n$/, '').slice(0, 1000)}`;
    // console output can arrive after the test result (batched RPC): forward it to the failure
    const failedId = failedTasks.get(log.taskId);
    if (failedId && cur) { send({ type: 'failure-console', runId: cur.runId, id: failedId, line }); return; }
    const a = consoleBuf.get(log.taskId) || [];
    if (a.join('').length < 4000) a.push(line);
    consoleBuf.set(log.taskId, a);
  },
  onTestCaseResult(t) {
    if (!cur) return;
    const r = t.result();
    const state = r.state === 'failed' ? 'fail' : r.state === 'passed' ? 'pass' : 'skip';
    // tests skipped only because of our name filter are not part of the run
    if (state === 'skip') { const f = cur.filter.get(slash(t.module.moduleId)); if (f && !f.has(t.fullName)) return; }
    const file = relp(t.module.moduleId);
    const line = t.location?.line ?? 0;
    const id = `${file}:${line} > ${t.fullName}`;
    const ms = Math.round((t.diagnostic()?.duration ?? 0) * 10) / 10;
    cur.counts[state]++;
    const ev = { ev: 'test', runId: cur.runId, id, state, ms };
    send({ type: 'ev', ev });
    if (state === 'fail') {
      const errs = r.errors || [];
      const console = consoleBuf.get(t.id);
      send({ type: 'failure', runId: cur.runId, id, file, line, name: t.fullName, errors: errs.map((e) => compactError(e, root, { full: true })), console });
      failedTasks.set(t.id, id);
    }
    consoleBuf.delete(t.id);
  },
  onTestModuleEnd(m) {
    if (!cur) return;
    const file = relp(m.moduleId);
    const errs = m.errors();
    const tests = [...m.children.allTests()];
    // load / collect failure: no test ran
    if (errs.length && !tests.some((t) => t.result().state === 'passed' || t.result().state === 'failed')) {
      cur.loadFailed.add(slash(m.moduleId));
      send({ type: 'failure', runId: cur.runId, id: `${file}:0 > (load)`, file, line: 0, name: '(load)', load: true, errors: errs.map((e) => compactError(e, root, { full: true })) });
    } else if (errs.length) {
      send({ type: 'failure', runId: cur.runId, id: `${file}:0 > (suite)`, file, line: 0, name: '(suite hook)', errors: errs.map((e) => compactError(e, root, { full: true })) });
    }
    send({ type: 'module-end', runId: cur.runId, file: slash(m.moduleId) });
  },
};

const vitest = await createVitest('test', {
  ...cliOptions, watch: false, run: true, reporters: [reporter], includeTaskLocation: true,
  ...(configFile ? { config: configFile } : {}), root,
  coverage: { enabled: false },
}, opts.instrument === false ? {} : { plugins: [await makePlugin()] });
async function makePlugin() {
  const { default: vtoInstrument } = await import(pathToFileURL(path.join(collectorDir, 'plugin.mjs')).href);
  makePlugin.inst = vtoInstrument();
  return makePlugin.inst;
}
makePlugin.inst?.vto.setVitest(vitest);
// pool override per lane (group lanes, raw pools such as forks for the node lane): applied to every
// project, because projects can set their own pool (vitest-guard-wrapped lanes keep vitest-guard's choice)
const RAW_POOL = { vm: 'vmThreads', shared: 'threads', forks: 'forks', threads: 'threads', vmThreads: 'vmThreads', vmForks: 'vmForks' };
const guarded = vitest.projects.some((p) => p.config.provide?.vitestGuard);
if (opts.group && RAW_POOL[pool] && !(guarded && (pool === 'vm' || pool === 'shared'))) {
  for (const p of vitest.projects) {
    p.config.pool = RAW_POOL[pool];
    // shared without vitest-guard's resets is not safe (vi.mock leaks, 309 failures in perf/RESULTS.md): keep isolation
    if (pool === 'shared') p.config.isolate = true;
  }
}
const setupFiles = new Set();
for (const p of vitest.projects) {
  const c = p.config;
  for (const f of c.setupFiles) setupFiles.add(slash(f));
  if (!c.setupFiles.includes(setupFile)) c.setupFiles.unshift(setupFile);
  if (opts.envProbe !== false && !c.setupFiles.includes(envProbe)) c.setupFiles.push(envProbe);
  c.includeTaskLocation = true;
  c.maxConcurrency = 1;
  if (c.sequence) c.sequence.concurrent = false;
  if (c.coverage) c.coverage.enabled = false;
}
// the main projects' mode; the quarantine sibling (forks) is a suffix, never the label (it used to win as the last project)
const guard = summarizeGuard(vitest.projects.map((p) => p.config));
const info = {
  vitest: vitestVersion, pool: [...new Set(vitest.projects.map((p) => p.config.pool))].join('+'), vitestGuard: guard?.mode ?? null, vitestGuardQuarantine: !!guard?.quarantine,
  configFile: vitest.vite.config.configFile ? slash(vitest.vite.config.configFile) : null,
  setupFiles: [...setupFiles], projects: vitest.projects.map((p) => p.name || ''), maxWorkers: vitest.config.maxWorkers,
  envDir: slash(vitest.vite.config.envDir || root),
};
send({ type: 'ready', info });

// ---- invalidation: stat every project module in the Vite graphs before a run -----------------------
const seen = new Map(); // file → mtimeMs:size
/** at run end: remember the stat of every module loaded; modules edited during the run are invalidated now */
function recordSeen(runStartMs) {
  for (const p of vitest.projects) for (const env of Object.values(p.vite.environments)) {
    const m = env.moduleGraph?.fileToModulesMap;
    if (!m) continue;
    for (const f of m.keys()) {
      if (typeof f !== 'string' || f.includes('/node_modules/') || seen.has(f)) continue;
      try { const s = fs.statSync(f); seen.set(f, `${s.mtimeMs}:${s.size}`); if (s.mtimeMs >= runStartMs - 5) { vitest.invalidateFile(f); vitest.watcher.invalidates.add(f); } } catch {}
    }
  }
}
function invalidateChanged() {
  const files = new Set();
  for (const p of vitest.projects) for (const env of Object.values(p.vite.environments)) {
    const m = env.moduleGraph?.fileToModulesMap;
    if (m) for (const f of m.keys()) if (typeof f === 'string' && !f.includes('/node_modules/')) files.add(f);
  }
  let n = 0;
  for (const f of files) {
    let sig;
    try { const s = fs.statSync(f); sig = `${s.mtimeMs}:${s.size}`; } catch { sig = 'gone'; }
    const prev = seen.get(f);
    seen.set(f, sig);
    if (prev !== undefined && prev !== sig) { vitest.invalidateFile(f); vitest.watcher.invalidates.add(f); n++; }
  }
  return n;
}

function findProjects(file) {
  const out = [];
  for (const p of vitest.projects) { try { if (p.matchesTestGlob(file)) out.push(p); } catch {} }
  return out;
}

// ---- "classic" output size: Vitest's own reporters writing into counting streams (SAVINGS.md) ----
// default (human CLI), minimal (what Vitest 5 picks under an AI agent: std-env isAgent) and verbose.
function measuredReporter(name, Cls) {
  const c = { name, chars: 0, endChars: 0, inEnd: false };
  const w = new Writable({ write(ch, enc, cb) { const n = String(ch).length; c.chars += n; if (c.inEnd) c.endChars += n; cb(); } });
  w.isTTY = false; w.columns = 120;
  let logger;
  try {
    logger = Object.create(vitest.logger, { outputStream: { value: w }, errorStream: { value: w }, console: { value: new Console(w, w) } });
  } catch { return null; }
  const ctx = new Proxy(vitest, { get(t, k) { return k === 'logger' ? logger : Reflect.get(t, k); } });
  let r;
  try { r = new Cls({ isTTY: false }); r.onInit(ctx); } catch (e) { send({ type: 'error', message: `classic ${name}: ${e.message}` }); return null; }
  const end = r.onTestRunEnd?.bind(r);
  r.onTestRunEnd = async (...a) => { c.inEnd = true; try { await end?.(...a); } finally { c.inEnd = false; } };
  r.__count = c;
  return r;
}
function attachClassic() {
  if (opts.measureClassic === false) return [];
  const rs = [['default', vitestNode.DefaultReporter], ['minimal', vitestNode.MinimalReporter], ['verbose', vitestNode.VerboseReporter]]
    .filter(([, C]) => C).map(([n, C]) => measuredReporter(n, C)).filter(Boolean);
  vitest.reporters.push(...rs);
  return rs;
}
function detachClassic(rs) {
  for (const r of rs) { const i = vitest.reporters.indexOf(r); if (i >= 0) vitest.reporters.splice(i, 1); }
  const out = {};
  for (const r of rs) out[r.__count.name] = { chars: r.__count.chars, endChars: r.__count.endChars };
  return out;
}

async function run(msg) {
  const t0 = performance.now();
  const cpu0 = process.cpuUsage();
  cur = { runId: msg.runId, counts: { pass: 0, fail: 0, skip: 0 }, loadFailed: new Set(), filter: new Map() };
  for (const s of msg.specs || []) if (s.names?.length) cur.filter.set(slash(path.resolve(root, s.file)), new Set(s.names));
  try {
    // the raw dir is deleted recursively: make sure the path to it holds no symlink (N5)
    const rawParts = path.relative(sd.root, rawDir).split(path.sep);
    if (rawParts[0] === '..' || path.isAbsolute(rawParts.join('/'))) throw new Error(`raw dir outside .vto/: ${rawDir}`);
    sd.verify(...rawParts);
    fs.rmSync(rawDir, { recursive: true, force: true });
    sd.verify(...rawParts);
    const invalidated = invalidateChanged();
    let specs;
    if (!msg.specs) {
      vitest.clearSpecificationsCache();
      specs = await vitest.globTestSpecifications();
    } else {
      specs = [];
      for (const s of msg.specs) {
        const file = slash(path.resolve(root, s.file)); // Vitest module ids use '/' on Windows too (D:/a/…); a '\\' id misses its name filter
        let projects = findProjects(file);
        if (!projects.length) projects = [vitest.getRootProject()];
        for (const p of projects) specs.push(p.createSpecification(file, s.names?.length ? { testNames: s.names } : undefined));
      }
    }
    const projects = {};
    for (const sp of specs) (projects[sp.project.name ? (opts.group ? `${sp.project.name}:${opts.group}` : sp.project.name) : opts.group || ''] ||= []).push(relp(sp.moduleId));
    const bail = msg.bail || 0;
    vitest.config.bail = bail;
    for (const p of vitest.projects) p.config.bail = bail;
    send({ type: 'started', runId: msg.runId, files: specs.length, invalidated, projects });
    const classicRs = attachClassic();
    const runStartMs = Date.now();
    try { await vitest.runTestSpecifications(specs, !msg.specs); } finally { cur.classic = detachClassic(classicRs); recordSeen(runStartMs); }
    const unhandled = vitest.state.getUnhandledErrors().map((e) => compactError(e, root, { full: true }));
    const cpu = process.cpuUsage(cpu0);
    send({ type: 'done', runId: msg.runId, counts: cur.counts, ms: Math.round(performance.now() - t0), cpuMs: Math.round((cpu.user + cpu.system) / 1000), rssMB: treeRssMB(),
      loadFailed: [...cur.loadFailed], files: specs.map((s) => slash(s.moduleId)), unhandled, cancelled: !!cur.cancelled, classic: cur.classic });
  } catch (e) {
    send({ type: 'done', runId: msg.runId, counts: cur.counts, ms: Math.round(performance.now() - t0), error: String(e?.stack || e), loadFailed: [...cur.loadFailed], files: [] });
  } finally {
    cur = null;
    failedTasks.clear();
    consoleBuf.clear();
  }
}

/** resident memory of this lane: the process itself plus, on Linux, its worker processes (forks pools) */
function treeRssMB() {
  let bytes = process.memoryUsage().rss;
  if (process.platform === 'linux') {
    const seen = new Set([process.pid]);
    const kids = (pid) => { try { return fs.readdirSync(`/proc/${pid}/task`).flatMap((t) => fs.readFileSync(`/proc/${pid}/task/${t}/children`, 'utf8').trim().split(/\s+/).filter(Boolean).map(Number)); } catch { return []; } };
    const stack = kids(process.pid);
    while (stack.length && seen.size < 500) {
      const pid = stack.pop();
      if (seen.has(pid)) continue;
      seen.add(pid);
      try { const m = /^VmRSS:\s+(\d+) kB/m.exec(fs.readFileSync(`/proc/${pid}/status`, 'utf8')); if (m) bytes += +m[1] * 1024; } catch {}
      stack.push(...kids(pid));
    }
  }
  return Math.round(bytes / 1048576);
}

let chain = Promise.resolve();
process.on('message', async (msg) => {
  if (msg.type === 'run') chain = chain.then(() => run(msg));
  else if (msg.type === 'cancel') { if (cur) { cur.cancelled = true; vitest.cancelCurrentRun('keyboard-input').catch(() => {}); } }
  else if (msg.type === 'list') {
    try { vitest.clearSpecificationsCache(); const s = await vitest.globTestSpecifications(); send({ type: 'list', reqId: msg.reqId, files: [...new Set(s.map((x) => slash(x.moduleId)))] }); }
    catch (e) { send({ type: 'list', reqId: msg.reqId, error: String(e) }); }
  } else if (msg.type === 'close') {
    await chain.catch(() => {});
    await vitest.close().catch(() => {});
    process.exit(0);
  }
});
process.on('disconnect', () => { vitest.close().finally(() => process.exit(0)); setTimeout(() => process.exit(0), 3000).unref(); });
