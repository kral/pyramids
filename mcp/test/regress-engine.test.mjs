const w = (root, f, s) => { const p = path.join(root, f); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };
const edit = (root, f, a, b) => { const p = path.join(root, f); const s = fs.readFileSync(p, 'utf8'); assert.ok(s.includes(a), `${f} has no ${a}`); fs.writeFileSync(p, s.replace(a, b)); };
