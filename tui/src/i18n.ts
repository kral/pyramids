export const dictionaries: Record<string, Dict> = { cs, en };

let current: Dict = en;
let currentLocale = 'en';

export function detectLocale(env: Record<string, string | undefined>): string {
  // English by default; Czech with VTO_LANG=cs (or --lang cs).
  const v = env.VTO_LANG || '';
  return /^cs/i.test(v) ? 'cs' : 'en';
}
export function setLocale(loc: string): void {
  current = dictionaries[loc] ?? en;
  currentLocale = dictionaries[loc] ? loc : 'en';
}
export function locale(): string { return currentLocale; }

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  let s: string = current[key] ?? en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  return s;
}
